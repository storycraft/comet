use accesskit::NodeId;
use comet_layout::{
    fragment::{FragmentKey, tree::FragmentTree},
    input::tree::LayoutInputTree,
};
use comet_tree::node::NodeKey;
use slotmap::{Key, KeyData, SecondaryMap};

use crate::A11yFlags;

/// The accessibility node of one fragment.
#[derive(Debug, Clone, PartialEq)]
pub struct A11yNode {
    /// The node last resolved for the fragment.
    pub node: accesskit::Node,
    pub flags: A11yFlags,
}

/// Accessibility nodes of the fragments under a root fragment, mirroring the
/// fragment tree one to one: every fragment, anonymous blocks, line boxes,
/// inline fragments and glyph runs included, has a node whose children are
/// the nodes of its child fragments.
///
/// Node ids are the fragment keys, so nodes keep their ids as long as their
/// fragments keep their keys. Built and updated by an
/// [`A11yTreeBuilder`](crate::builder::A11yTreeBuilder).
///
/// Keys are generational: nodes left behind by deleted fragments are never
/// returned for fragments reusing their slots, and are overwritten when those
/// are resolved. A build from a root fragment without a node drops them.
#[derive(Debug, Default)]
pub struct A11yTree {
    pub(crate) nodes: SecondaryMap<FragmentKey, A11yNode>,
    /// Fragments whose nodes changed since the last update.
    pub(crate) changed: Vec<FragmentKey>,
}

impl A11yTree {
    pub fn new() -> Self {
        Self::default()
    }

    /// Fragments whose nodes changed since the last
    /// [update](Self::take_update), possibly more than once each.
    pub fn changed(&self) -> &[FragmentKey] {
        &self.changed
    }

    /// The nodes changed since the last update, for the nodes of an
    /// [`accesskit::TreeUpdate`], and clear the [changed](Self::changed)
    /// list. After a build from a new root, they are every node of the tree.
    pub fn take_update(&mut self) -> Vec<(NodeId, accesskit::Node)> {
        let mut changed = core::mem::take(&mut self.changed);
        changed.sort_unstable();
        changed.dedup();

        let nodes = changed
            .iter()
            .filter_map(|&key| Some((node_id(key), self.nodes.get(key)?.node.clone())))
            .collect();
        // Keep the buffer.
        changed.clear();
        self.changed = changed;

        nodes
    }

    /// The node of a fragment.
    pub fn get(&self, key: FragmentKey) -> Option<&A11yNode> {
        self.nodes.get(key)
    }

    /// Mark the node of a fragment [`A11yFlags::DIRTY`], and its ancestors
    /// [`A11yFlags::CHILD_DIRTY`] up to the root fragment, so the next build
    /// resolves it again. Fragments without nodes are resolved anyway, so
    /// only their ancestors are marked.
    pub fn mark(&mut self, fragments: &FragmentTree, key: FragmentKey) {
        if let Some(node) = self.nodes.get_mut(key) {
            node.flags.insert(A11yFlags::DIRTY);
        }

        let mut ancestor = fragments.items.parent(key);
        while let Some(key) = ancestor {
            if let Some(node) = self.nodes.get_mut(key) {
                // Ancestors of a marked node are marked already.
                if node.flags.contains(A11yFlags::CHILD_DIRTY) {
                    break;
                }
                node.flags.insert(A11yFlags::CHILD_DIRTY);
            }

            ancestor = fragments.items.parent(key);
        }
    }

    /// [Mark](Self::mark) the fragments generated by a source node: its box,
    /// or its inline and glyph run fragments on every line. Nodes without
    /// fragments are ignored.
    pub fn mark_node(&mut self, inputs: &LayoutInputTree, fragments: &FragmentTree, node: NodeKey) {
        let Some(item) = inputs.item_for_node(node) else {
            return;
        };

        for key in fragments.fragments(item) {
            self.mark(fragments, key);
        }
    }

    pub fn clear(&mut self) {
        self.nodes.clear();
        self.changed.clear();
    }
}

/// The node id of a fragment.
pub fn node_id(key: FragmentKey) -> NodeId {
    NodeId(key.data().as_ffi())
}

/// The fragment of a node id, such as the target of an action request.
pub fn fragment_key(id: NodeId) -> FragmentKey {
    KeyData::from_ffi(id.0).into()
}
