//! Flattened inline layout of an inline formatting context.

pub mod collect;
pub mod input;

use core::{iter::FusedIterator, ops::Range};

use rustc_hash::FxHashMap;
use slotmap::{Key, KeyData};

use super::{BoxFragmentKey, FragmentGeometry};
use crate::{
    fragment::offset::{to_shaped, to_source},
    fragment::state::NodeLayoutBits,
    input::LayoutInputKey,
};

/// Text, shaped layout and items of one inline formatting context, owned by
/// the box establishing it.
#[derive(Debug, Default)]
pub struct InlineLayout {
    /// Concatenated text of the inline content. Inline boxes in flow are
    /// U+FFFC characters.
    pub text: String,
    /// Layout whose span brushes are the items owning the spans, and whose
    /// inline box ids are the items of the boxes, see [`inline_box_id`].
    pub layout: parley::Layout<LayoutInputKey>,
    /// Where the text items and inline elements end up in [`Self::text`], in
    /// tree order, so sorted by start. Text ranges do not overlap; an inline
    /// element covers the ranges of its content.
    pub offset_mapping: Vec<OffsetEntry>,
    /// Lines, inline element pieces, boxes and glyph runs, in preorder.
    pub items: Vec<InlineItem>,
    /// Box fragment of each box inside the inline content: atomic inline and
    /// out-of-flow boxes, the children of the owner. Set
    /// when the inline content is built, and read when laying out the lines.
    pub atomics: FxHashMap<LayoutInputKey, BoxFragmentKey>,
    /// Whether the inline content is built: its text shaped, and the boxes
    /// inside matching the children of the owner. Until then, the other
    /// fields hold the previous content, if any.
    pub(crate) built: bool,
    /// For a run of inline content split by block level boxes, the block
    /// level box it follows; `None` for the first run, or content that is
    /// not split. Kept across builds.
    pub(crate) run_start: Option<LayoutInputKey>,
    /// [Propagated](NodeLayoutBits::PROPAGATED) bits of the box styles of
    /// the inline elements in the inline content, which have no boxes of
    /// their own. Part of the bits of the owner. Set by a full build, and
    /// only extended by box changes until the next one.
    pub(crate) content_bits: NodeLayoutBits,
    /// First and last line baselines relative to the content box top.
    pub(crate) first_baseline: Option<f32>,
    pub(crate) last_baseline: Option<f32>,
    /// Offset of the [`Self::layout`] coordinates from the owner's border box.
    pub(crate) origin: kurbo::Vec2,
}

/// Range of an item in [`InlineLayout::text`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OffsetEntry {
    pub source: LayoutInputKey,
    pub range: Range<usize>,
    /// Whether the item is a text item, rather than an inline element.
    pub text: bool,
}

/// The id of the Parley inline box of an item: an atomic inline, inline
/// part or out-of-flow box, or an empty inline element.
pub fn inline_box_id(source: LayoutInputKey) -> u64 {
    source.data().as_ffi()
}

/// The item of a Parley inline box, from its [id](inline_box_id).
pub fn inline_box_source(id: u64) -> LayoutInputKey {
    KeyData::from_ffi(id).into()
}

/// An item of an inline layout.
#[derive(Debug, Clone, PartialEq)]
pub struct InlineItem {
    /// Item generating this one. Lines belong to the owner of the layout.
    pub source: LayoutInputKey,
    pub kind: InlineItemKind,
    /// Number of items in its subtree, following it.
    pub descendants: u32,
    pub link: InlineLink,
    /// Geometry relative to the border box of the owner of the layout.
    /// Padding and border are zero.
    pub geometry: FragmentGeometry,
    /// Baseline relative to the top of the item.
    pub baseline: f32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum InlineItemKind {
    /// Line box, indexing the lines of the layout.
    Line { line: u32 },
    /// Piece of an inline element on one line when `child` is `None`, else
    /// an atomic inline or out-of-flow box.
    Box { child: Option<BoxFragmentKey> },
    /// Glyph run, indexing the items of a line of the layout.
    Run { line: u32, run: u32 },
}

/// Links the items generated by one source across lines, as index deltas.
/// Zero means no link.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash)]
pub struct InlineLink {
    pub prev: i32,
    pub next: i32,
}

impl InlineItem {
    pub const fn is_line(&self) -> bool {
        matches!(self.kind, InlineItemKind::Line { .. })
    }

    pub const fn is_run(&self) -> bool {
        matches!(self.kind, InlineItemKind::Run { .. })
    }

    /// The box fragment of an atomic inline or out-of-flow box.
    pub const fn child_box(&self) -> Option<BoxFragmentKey> {
        match self.kind {
            InlineItemKind::Box { child } => child,
            _ => None,
        }
    }
}

impl InlineLayout {
    pub fn new() -> Self {
        Self::default()
    }

    /// Offset of the [`Self::layout`] coordinates in the local coordinates
    /// of the owner's border box: its content box offset.
    pub fn origin(&self) -> kurbo::Vec2 {
        self.origin
    }

    /// Whether the inline content is built. An inline formatting context is
    /// built when it is laid out.
    pub fn is_built(&self) -> bool {
        self.built
    }

    /// For a run of inline content split by block level boxes, the block
    /// level box it follows. The inline elements holding it are split by it,
    /// see [`FragmentTree::is_split_before`](crate::fragment2::FragmentTree::is_split_before).
    pub fn run_start(&self) -> Option<LayoutInputKey> {
        self.run_start
    }

    /// First line baseline relative to the content box top.
    pub fn first_baseline(&self) -> Option<f32> {
        self.first_baseline
    }

    /// Last line baseline relative to the content box top.
    pub fn last_baseline(&self) -> Option<f32> {
        self.last_baseline
    }

    /// Indices of the subtree of an item, excluding itself.
    pub fn subtree(&self, index: usize) -> Range<usize> {
        let end = index + 1 + self.items[index].descendants as usize;

        index + 1..end
    }

    /// Indices of the top level items: the lines.
    pub fn roots(&self) -> Siblings<'_> {
        Siblings {
            items: &self.items,
            next: 0,
            end: self.items.len(),
        }
    }

    /// Indices of the direct children of an item.
    pub fn children(&self, index: usize) -> Siblings<'_> {
        let range = self.subtree(index);

        Siblings {
            items: &self.items,
            next: range.start,
            end: range.end,
        }
    }

    /// Index of the previous item of the same source.
    pub fn prev(&self, index: usize) -> Option<usize> {
        offset(index, self.items[index].link.prev)
    }

    /// Index of the next item of the same source.
    pub fn next(&self, index: usize) -> Option<usize> {
        offset(index, self.items[index].link.next)
    }

    /// Indices of the items generated by `source` in layout order.
    pub fn items_of(&self, source: LayoutInputKey) -> Linked<'_> {
        Linked {
            layout: self,
            next: self
                .items
                .iter()
                .position(|item| item.source == source && !item.is_line()),
        }
    }

    /// The range of an item in [`Self::text`].
    pub fn range(&self, source: LayoutInputKey) -> Option<Range<usize>> {
        self.offset_mapping
            .iter()
            .find(|entry| entry.source == source)
            .map(|entry| entry.range.clone())
    }

    /// The index in [`Self::text`] of `index` in `source`, the text of the
    /// text item `item`. An index in white space removed by white space
    /// processing maps to where it was removed, and one past the end of
    /// `source` to the end of its range. `None` if the layout does not hold
    /// the item.
    pub fn layout_index(&self, item: LayoutInputKey, source: &str, index: usize) -> Option<usize> {
        let range = self.range(item)?;
        let shaped = self.text.get(range.clone())?;

        Some(range.start + to_shaped(source, shaped, index))
    }

    /// The index in `source`, the text of the text item `item`, of `index`
    /// in [`Self::text`], clamped to the range of the item. Of the indices
    /// mapping to the same place, the first. `None` if the layout does not
    /// hold the item.
    pub fn source_index(&self, item: LayoutInputKey, source: &str, index: usize) -> Option<usize> {
        let range = self.range(item)?;
        let shaped = self.text.get(range.clone())?;
        let index = index.clamp(range.start, range.end) - range.start;

        Some(to_source(source, shaped, index))
    }

    /// The text item holding `index` in [`Self::text`]. At the boundary of
    /// two items, `affinity` picks the one before or after it. Outside of
    /// every item, such as at an inline box, the closest item before it,
    /// else the first after it. `None` without text items.
    pub fn item_at(&self, index: usize, affinity: parley::Affinity) -> Option<LayoutInputKey> {
        // Entries are sorted by start, and text ranges do not overlap.
        let split = self
            .offset_mapping
            .partition_point(|entry| entry.range.start <= index);
        let (before, after) = self.offset_mapping.split_at(split);
        let mut before = before.iter().rev().filter(|entry| entry.text);

        if affinity == parley::Affinity::Upstream
            && let Some(entry) = before
                .clone()
                .take_while(|entry| entry.range.end >= index)
                .find(|entry| entry.range.end == index && !entry.range.is_empty())
        {
            return Some(entry.source);
        }

        before
            .next()
            .or_else(|| after.iter().find(|entry| entry.text))
            .map(|entry| entry.source)
    }
}

/// `index` moved by `delta`, or `None` for a zero delta.
fn offset(index: usize, delta: i32) -> Option<usize> {
    (delta != 0).then(|| index.wrapping_add_signed(delta as isize))
}

/// Indices of sibling items, skipping their subtrees.
pub struct Siblings<'a> {
    items: &'a [InlineItem],
    next: usize,
    end: usize,
}

impl Iterator for Siblings<'_> {
    type Item = usize;

    fn next(&mut self) -> Option<usize> {
        let index = self.next;

        if index >= self.end {
            return None;
        }

        self.next = index + 1 + self.items[index].descendants as usize;
        Some(index)
    }
}

impl FusedIterator for Siblings<'_> {}

/// Indices of the items of one source, following [`InlineLink::next`].
pub struct Linked<'a> {
    layout: &'a InlineLayout,
    next: Option<usize>,
}

impl Iterator for Linked<'_> {
    type Item = usize;

    fn next(&mut self) -> Option<usize> {
        let index = self.next.take()?;
        self.next = self.layout.next(index);

        Some(index)
    }
}

impl FusedIterator for Linked<'_> {}
