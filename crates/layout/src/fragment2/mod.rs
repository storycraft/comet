//! Box fragment tree with flattened inline layouts.
//!
//! Only boxes are tree nodes. Each inline formatting context is held by the
//! box establishing it as one [`InlineLayout`]: its text, Parley layout and a
//! flat, preorder list of [`InlineItem`]s for lines, inline element pieces and
//! glyph runs. Block level boxes inside inline content are laid out on lines
//! of that same layout, so an inline element split around them keeps all of
//! its pieces in one item list.

