use comet_slotmap_tree::SlotTree;
use slotmap::SecondaryMap;

use super::{BoxFragment, BoxFragmentKey, FragmentGeometry, FragmentRef, InlineLayout};
use crate::input::{LayoutInputKey, tree::LayoutInputTree};

/// Box fragments of a layout input tree, each owning the inline layout of the
/// inline formatting context it establishes.
#[derive(Debug, Default)]
pub struct FragmentTree {
    /// Box fragments. A box is a child of the box of its nearest ancestor
    /// item generating one. Boxes missing from the source lookup are
    /// [anonymous](Self::is_anonymous). Use [`Self::insert`],
    /// [`Self::insert_anonymous`] and [`Self::delete`] to keep the source
    /// lookup in step.
    pub boxes: SlotTree<BoxFragmentKey, BoxFragment>,
    /// Box fragment generated by each item.
    by_source: SecondaryMap<LayoutInputKey, BoxFragmentKey>,
}

impl FragmentTree {
    pub fn new() -> Self {
        Self::default()
    }

    /// The box fragment generated by an item.
    pub fn box_fragment(&self, source: LayoutInputKey) -> Option<BoxFragmentKey> {
        self.by_source
            .get(source)
            .copied()
            .filter(|&key| self.boxes.get(key).is_some_and(|bx| bx.source == source))
    }

    pub fn get(&self, key: BoxFragmentKey) -> Option<&BoxFragment> {
        self.boxes.get(key)
    }

    pub fn get_mut(&mut self, key: BoxFragmentKey) -> Option<&mut BoxFragment> {
        self.boxes.get_mut(key)
    }

    /// The inline layout of the inline formatting context a box establishes.
    pub fn inline_layout(&self, key: BoxFragmentKey) -> Option<&InlineLayout> {
        self.boxes.get(key)?.inline()
    }

    /// The box whose inline layout holds the inline content item `item` of
    /// `tree`: the box of its nearest ancestor generating one, if it
    /// establishes an inline formatting context, or the first run of that
    /// box holding the item, if its inline content is mixed. Runs not built
    /// yet hold nothing.
    pub fn inline_owner(
        &self,
        tree: &LayoutInputTree,
        item: LayoutInputKey,
    ) -> Option<BoxFragmentKey> {
        let owner = std::iter::successors(tree.items.parent(item), |&key| tree.items.parent(key))
            .find_map(|key| self.box_fragment(key))?;
        let layout = &self.boxes[owner].child_layout;

        if layout.is_inline() {
            return Some(owner);
        }

        if !layout.is_mixed_inline() {
            return None;
        }

        self.runs(owner).find(|&run| {
            self.inline_layout(run).is_some_and(|inline| {
                inline.range(item).is_some() || inline.atomics.contains_key(&item)
            })
        })
    }

    /// The run boxes of a [mixed inline](super::ChildLayoutType::MixedInline)
    /// box, in flow order, following their links.
    pub fn runs(&self, owner: BoxFragmentKey) -> SplitBoxes<'_> {
        let first = self
            .boxes
            .get(owner)
            .and_then(|fragment| fragment.child_layout.first_run());

        SplitBoxes {
            tree: self,
            next: first,
        }
    }

    /// The boxes split from the same source as the box `key`, including
    /// itself, in flow order, following their [links](super::BoxFragmentLink).
    pub fn split_boxes(&self, key: BoxFragmentKey) -> SplitBoxes<'_> {
        let mut first = self.boxes.get(key).map(|_| key);

        while let Some(prev) = first.and_then(|key| self.boxes[key].link.prev) {
            first = Some(prev);
        }

        SplitBoxes {
            tree: self,
            next: first,
        }
    }

    /// The fragments generated by an item, in layout order. A box generating
    /// item yields its box. A text item or inline element yields its items
    /// in the inline layouts holding it: across the lines of one layout,
    /// and across the runs of a mixed inline box, following the inline
    /// elements split by its block level boxes. Lines and run boxes are not
    /// included.
    pub fn fragments<'a>(
        &'a self,
        tree: &'a LayoutInputTree,
        item: LayoutInputKey,
    ) -> impl Iterator<Item = FragmentRef> + 'a {
        let own = self.box_fragment(item).map(FragmentRef::Box);
        let layouts = match own {
            Some(_) => None,
            None => self.inline_owner(tree, item),
        };

        let runs = layouts.into_iter().flat_map(move |first| {
            self.split_boxes(first)
                .skip_while(move |&run| run != first)
                .take_while(move |&run| {
                    // A later run continues the item only when it was split.
                    run == first
                        || self
                            .inline_layout(run)
                            .is_some_and(|inline| inline.reopened.contains(&item))
                })
        });

        own.into_iter().chain(runs.flat_map(move |owner| {
            self.inline_layout(owner)
                .into_iter()
                .flat_map(move |inline| inline.items_of(item))
                .map(move |index| FragmentRef::Inline {
                    owner,
                    index: index as u32,
                })
        }))
    }

    /// The source item of a fragment.
    pub fn source(&self, fragment: FragmentRef) -> Option<LayoutInputKey> {
        match fragment {
            FragmentRef::Box(key) => Some(self.boxes.get(key)?.source),
            FragmentRef::Inline { owner, index } => {
                Some(self.inline_layout(owner)?.items.get(index as usize)?.source)
            }
        }
    }

    /// The geometry of a fragment. Inline items are relative to the border
    /// box of their owner.
    pub fn geometry(&self, fragment: FragmentRef) -> Option<&FragmentGeometry> {
        match fragment {
            FragmentRef::Box(key) => Some(&self.boxes.get(key)?.layout.geometry),
            FragmentRef::Inline { owner, index } => Some(
                &self
                    .inline_layout(owner)?
                    .items
                    .get(index as usize)?
                    .geometry,
            ),
        }
    }

    /// The largest scroll offset of a box clipping and scrolling its
    /// overflow: how far its content overflows its padding box towards the
    /// right and bottom. `None` if the box is not in the tree.
    ///
    /// Its overflow includes its border box, so only content passing the
    /// border box edge scrolls, by that excess and the border width.
    pub fn scroll_range(&self, key: BoxFragmentKey) -> Option<kurbo::Vec2> {
        let geometry = &self.boxes.get(key)?.layout.geometry;
        let range = |excess: f64, border: f64| {
            if excess > 0.0 { excess + border } else { 0.0 }
        };

        Some(kurbo::Vec2::new(
            range(
                geometry.overflow.x1 - geometry.size.width,
                geometry.border.right_bottom.x,
            ),
            range(
                geometry.overflow.y1 - geometry.size.height,
                geometry.border.right_bottom.y,
            ),
        ))
    }

    /// Whether a box fragment is anonymous: it is not the box generated by
    /// its source, so [`Self::box_fragment`] never returns it. `false` if the
    /// box is not in the tree.
    pub fn is_anonymous(&self, key: BoxFragmentKey) -> bool {
        self.boxes
            .get(key)
            .is_some_and(|bx| self.by_source.get(bx.source) != Some(&key))
    }

    /// Insert a detached box fragment, and make it the box of its source.
    pub(crate) fn insert(&mut self, fragment: BoxFragment) -> BoxFragmentKey {
        let source = fragment.source;
        let key = self.boxes.insert(fragment);
        self.by_source.insert(source, key);

        key
    }

    /// Insert a detached anonymous box fragment, leaving the box of its
    /// source as it is.
    pub(crate) fn insert_anonymous(&mut self, fragment: BoxFragment) -> BoxFragmentKey {
        self.boxes.insert(fragment)
    }

    /// Delete a box fragment and its descendants, and their source lookups.
    pub(crate) fn delete(&mut self, key: BoxFragmentKey) -> Option<BoxFragment> {
        self.boxes.get(key)?;

        for key in self.boxes.descendants(key) {
            let source = self.boxes[key].source;

            if self.by_source.get(source) == Some(&key) {
                self.by_source.remove(source);
            }
        }

        self.boxes.delete_node(key)
    }

    pub fn clear(&mut self) {
        self.boxes.clear();
        self.by_source.clear();
    }
}

/// Box fragments following their [links](super::BoxFragmentLink), returned
/// by [`FragmentTree::split_boxes`] and [`FragmentTree::runs`].
pub struct SplitBoxes<'a> {
    tree: &'a FragmentTree,
    next: Option<BoxFragmentKey>,
}

impl Iterator for SplitBoxes<'_> {
    type Item = BoxFragmentKey;

    fn next(&mut self) -> Option<BoxFragmentKey> {
        let key = self.next.take()?;
        // Stale keys end the chain; deleted box keys are never reused.
        let fragment = self.tree.boxes.get(key)?;
        self.next = fragment.link.next;

        Some(key)
    }
}

impl core::iter::FusedIterator for SplitBoxes<'_> {}
