//! Incremental fragment tree built from a [`LayoutInputTree`](crate::input::tree::LayoutInputTree).
//!
//! Block level boxes are laid out by Taffy and written into their box fragments
//! in place. Inline formatting contexts are laid out by Parley and split into
//! line boxes, inline span fragments and glyph runs. Inline content containing
//! block boxes is split into anonymous blocks, laid out between the block boxes
//! by Taffy's block algorithm so their margins collapse.

pub(crate) mod adapter;
pub(crate) mod engine;
pub mod state;

pub mod builder;
pub mod iter;
pub mod tree;

use slotmap::new_key_type;

use crate::{
    input::LayoutInputKey,
    style::geometry::{Point, Rect, Size},
};

new_key_type! {
    pub struct FragmentKey;
    /// Retained layout state of a box or anonymous block fragment, stored in
    /// its [`FragmentTree`](tree::FragmentTree).
    pub struct StateKey;
}

/// Source text and its shaped layout, retained together for rendering.
///
/// Owned by the fragment containing the lines: the box of an inline formatting
/// context, or an anonymous block. `GlyphRun` and `Line` fragments index into
/// the lines of `layout`.
pub struct InlineLayout {
    pub text: String,
    /// Layout whose span brushes are the items owning the spans.
    pub layout: parley::Layout<Option<LayoutInputKey>>,
    /// Items of the inline boxes in `layout`, indexed by inline box id.
    pub(crate) boxes: Vec<LayoutInputKey>,
    /// Whether `layout` matches the current inline content. Line breaking
    /// alone does not require reshaping.
    pub(crate) shaped: bool,
    /// First and last line baselines relative to the content box top.
    pub(crate) first_baseline: Option<f32>,
    pub(crate) last_baseline: Option<f32>,
    /// Line fragment of each line of `layout`, by line index. Filled when the
    /// lines are emitted.
    pub(crate) lines: Vec<FragmentKey>,
    /// Leaf fragment of each emitted line item, sorted by line and text
    /// range. Filled when the lines are emitted.
    pub(crate) runs: Vec<RunEntry>,
}

impl InlineLayout {
    /// Line fragment of each line of [`Self::layout`], by line index.
    pub fn lines(&self) -> &[FragmentKey] {
        &self.lines
    }

    /// Offset of the [`Self::layout`] coordinates in the local coordinates
    /// of the fragment owning it, `tree`: its content box offset. `None`
    /// before the lines are emitted.
    pub fn origin(&self, tree: &tree::FragmentTree) -> Option<kurbo::Vec2> {
        let metrics = self.layout.get(0)?.metrics();
        let line = tree.items.get(*self.lines.first()?)?;

        Some(kurbo::Vec2::new(
            line.layout.location.x - f64::from(metrics.inline_min_coord),
            line.layout.location.y - f64::from(metrics.block_min_coord),
        ))
    }
}

/// A leaf fragment of an emitted line: a glyph run, an atomic inline box or
/// an empty inline element, with its logical text range.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct RunEntry {
    pub fragment: FragmentKey,
    /// Line index in the inline layout.
    pub line: usize,
    /// Index into the line's positioned items.
    pub item: usize,
    /// Byte range in the inline layout's text. Inline boxes cover their
    /// U+FFFC character.
    pub start: usize,
    pub end: usize,
}

/// Links all fragments generated by one source node, including line splits.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct FragmentLink {
    pub prev: Option<FragmentKey>,
    pub next: Option<FragmentKey>,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum FragmentItem {
    /// Box of a block level or atomic inline item. Box fragments keep their keys
    /// across rebuilds.
    Box { state: StateKey },
    /// Block containing one run of inline content of `source`, between the
    /// block boxes interrupting it. It holds the run's line boxes.
    AnonymousBlock { state: StateKey },
    /// Line box of the inline layout owned by its parent fragment.
    Line { line: usize },
    /// Index into the owning inline layout's positioned line items.
    GlyphRun { line: usize, item: usize },
    /// Part of an inline element placed on one line.
    Inline { line: usize },
}

impl FragmentItem {
    /// The layout state of a box or anonymous block.
    pub const fn state(&self) -> Option<StateKey> {
        match *self {
            Self::Box { state } | Self::AnonymousBlock { state } => Some(state),
            _ => None,
        }
    }

    pub const fn is_box(&self) -> bool {
        matches!(self, Self::Box { .. })
    }

    pub const fn is_anonymous_block(&self) -> bool {
        matches!(self, Self::AnonymousBlock { .. })
    }
}

#[derive(Debug, Clone)]
pub struct Fragment {
    /// Item generating this fragment. Line boxes and anonymous blocks belong to
    /// the item establishing the inline formatting context.
    pub source: LayoutInputKey,
    pub item: FragmentItem,
    pub layout: FragmentBox,
    pub link: FragmentLink,
}

impl Fragment {
    pub(crate) fn new(source: LayoutInputKey, item: FragmentItem, layout: FragmentBox) -> Self {
        Self {
            source,
            item,
            layout,
            link: FragmentLink::default(),
        }
    }
}

/// Computed geometry of a fragment.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct FragmentBox {
    /// Coordinates relative to the parent fragment.
    pub location: Point<f64>,
    pub size: Size<f64>,
    pub padding: Rect<f64>,
    pub border: Rect<f64>,
    pub baseline: Option<f64>,
    /// Layout overflow: the area covered by the border box and by the
    /// overflow of every descendant fragment, in local coordinates with the
    /// border box's top-left corner at the origin. Descendants clipped by a
    /// box clipping its overflow only contribute that box's border box.
    ///
    /// Boxes and anonymous blocks take it from Taffy's scrollable overflow
    /// rectangle, extended by their inline content and by the out-of-flow
    /// boxes placed under them. Transforms are not applied, and neither is
    /// paint outside of layout, such as outlines or glyph ink.
    pub overflow: kurbo::Rect,
}

impl FragmentBox {
    /// The border box, in local coordinates.
    pub fn border_box(&self) -> kurbo::Rect {
        kurbo::Rect::new(0.0, 0.0, self.size.width, self.size.height)
    }

    /// The area covered by the fragment and its descendants, in the local
    /// coordinates of its parent: its [overflow](Self::overflow), placed at
    /// its location.
    pub fn extent(&self) -> kurbo::Rect {
        self.overflow + kurbo::Vec2::new(self.location.x, self.location.y)
    }
}
