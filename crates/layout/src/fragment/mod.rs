//! Incremental fragment tree built from a [`LayoutInputTree`](crate::input::tree::LayoutInputTree).
//!
//! Block level boxes are laid out by Taffy and written into their box fragments
//! in place. Inline formatting contexts are laid out by Parley and split into
//! line boxes, inline span fragments, glyph runs and the block boxes that
//! interrupt the inline content.

mod adapter;
pub(crate) mod engine;
mod state;

pub mod builder;
pub mod iterator;
pub mod tree;

use comet_tree::node::NodeKey;
use slotmap::new_key_type;

use crate::{
    input::LayoutInputKey,
    style::geometry::{Point, Rect, Size},
};

pub use crate::parley::{TextStyle, default_text_style};
pub use builder::FragmentTreeBuilder;
pub use iterator::Fragments;
pub use tree::FragmentTree;

new_key_type! { pub struct FragmentKey; }

/// Source text and its shaped layout, retained together for rendering.
///
/// `GlyphRun` and `Line` fragments index into the lines of `layout`.
pub struct InlineLayout {
    pub text: String,
    pub layout: parley::Layout<Option<NodeKey>>,
    /// Whether `layout` matches the current inline content. Line breaking
    /// alone does not require reshaping.
    pub(crate) shaped: bool,
    /// First and last line baselines relative to the content box top.
    pub(crate) first_baseline: Option<f32>,
    pub(crate) last_baseline: Option<f32>,
}

/// Links all fragments generated by one source node, including line splits.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct FragmentLink {
    pub prev: Option<FragmentKey>,
    pub next: Option<FragmentKey>,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum FragmentItem {
    /// Box of a block level or atomic inline item. Box fragments keep their keys
    /// across rebuilds.
    Box,
    /// Line box of the inline layout owned by `source`.
    Line { line: usize },
    /// Index into the owning inline layout's positioned line items.
    GlyphRun { line: usize, item: usize },
    /// Part of an inline element placed on one line.
    Inline { line: usize },
}

#[derive(Debug, Clone)]
pub struct Fragment {
    /// Item generating this fragment. Line boxes belong to the item
    /// establishing the inline formatting context.
    pub source: LayoutInputKey,
    pub item: FragmentItem,
    pub layout: FragmentBox,
    pub link: FragmentLink,
}

impl Fragment {
    pub(crate) fn new(source: LayoutInputKey, item: FragmentItem, layout: FragmentBox) -> Self {
        Self {
            source,
            item,
            layout,
            link: FragmentLink::default(),
        }
    }
}

/// Computed geometry of a fragment.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct FragmentBox {
    /// Coordinates relative to the parent fragment.
    pub location: Point<f64>,
    pub size: Size<f64>,
    pub padding: Rect<f64>,
    pub border: Rect<f64>,
    pub baseline: Option<f64>,
}
