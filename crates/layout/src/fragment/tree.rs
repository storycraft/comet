use slotmap::{SecondaryMap, SparseSecondaryMap};

use super::{Fragment, FragmentKey, InlineLayout, iter::Fragments, state::NodeState};
use crate::{input::LayoutInputKey, slot_tree::SlotTree, style::LayoutConstraint};

#[derive(Default)]
pub struct FragmentTree {
    pub items: SlotTree<FragmentKey, Fragment>,
    /// Shaped text of each inline formatting context root, retained for
    /// rendering glyph runs by their line and item indices.
    pub inline_layouts: SparseSecondaryMap<LayoutInputKey, InlineLayout>,
    /// Retained layout state of every box generating item.
    pub(crate) states: SecondaryMap<LayoutInputKey, NodeState>,
    /// First fragment of each inline and text item, split across lines.
    pub(crate) first: SparseSecondaryMap<LayoutInputKey, FragmentKey>,
    /// Constraint of the latest build of each root.
    pub(crate) constraints: SparseSecondaryMap<LayoutInputKey, LayoutConstraint>,
}

impl FragmentTree {
    pub fn new() -> Self {
        Self::default()
    }

    /// The box fragment generated for a block level or atomic inline item,
    /// or for a root item.
    pub fn box_fragment(&self, key: LayoutInputKey) -> Option<FragmentKey> {
        self.states
            .get(key)
            .map(|state| state.fragment)
            .filter(|&fragment| self.items.get(fragment).is_some())
    }

    /// Iterate the fragments generated by an item in layout order.
    ///
    /// A box generating item yields its box fragment. Inline and text items
    /// yield their inline and glyph run fragments across lines, linked by
    /// [`FragmentLink`](super::FragmentLink). Line boxes are not included.
    /// Items without fragments yield nothing.
    pub fn fragments(&self, key: LayoutInputKey) -> Fragments<'_> {
        Fragments::new(self, key)
    }

    /// The constraint used to build the root containing this fragment.
    pub fn layout_constraint(&self, mut key: FragmentKey) -> Option<&LayoutConstraint> {
        while let Some(parent) = self.items.parent(key) {
            key = parent;
        }

        self.constraints.get(self.items.get(key)?.source)
    }

    pub fn clear(&mut self) {
        self.items.clear();
        self.inline_layouts.clear();
        self.states.clear();
        self.first.clear();
        self.constraints.clear();
    }
}
