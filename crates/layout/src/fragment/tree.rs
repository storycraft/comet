use slotmap::{SecondaryMap, SlotMap};

use super::{
    Fragment, FragmentBox, FragmentItem, FragmentKey, InlineLayout, StateKey, iter::Fragments,
    state::NodeState,
};
use crate::{input::LayoutInputKey, taffy::style::Style};
use comet_slotmap_tree::SlotTree;

#[derive(Default)]
pub struct FragmentTree {
    pub items: SlotTree<FragmentKey, Fragment>,
    /// Layout state of each box and anonymous block fragment, keyed by the
    /// state key in its [`FragmentItem`].
    pub(crate) states: SlotMap<StateKey, NodeState>,
    /// First fragment of each item: its box, or its first inline or glyph
    /// run fragment.
    pub(crate) first: SecondaryMap<LayoutInputKey, FragmentKey>,
    /// Generation of the latest build, increasing with every build.
    pub(crate) generation: u64,
    /// Fragments created or moved or resized in the current build.
    pub(crate) changed: Vec<FragmentKey>,
}

impl FragmentTree {
    pub fn new() -> Self {
        Self::default()
    }

    /// The box fragment generated for a block level or atomic inline item,
    /// a child of a container, or a root item.
    pub fn box_fragment(&self, key: LayoutInputKey) -> Option<FragmentKey> {
        self.first.get(key).copied().filter(|&fragment| {
            self.items.get(fragment).is_some_and(|item| {
                matches!(item.item, FragmentItem::Box { state } if self.states.contains_key(state))
                    && item.source == key
            })
        })
    }

    /// Iterate the fragments generated by an item in layout order.
    ///
    /// A box generating item yields its box fragment. Inline and text items
    /// yield their inline and glyph run fragments across lines, linked by
    /// [`FragmentLink`](super::FragmentLink). Line boxes and anonymous blocks
    /// are not included. Items without fragments yield nothing.
    pub fn fragments(&self, key: LayoutInputKey) -> Fragments<'_> {
        Fragments::new(self, key)
    }

    /// The inline layout a line belongs to, given the line fragment or the
    /// fragment owning its lines.
    pub fn inline_layout(&self, key: FragmentKey) -> Option<&InlineLayout> {
        self.get_inline(key)
            .or_else(|| self.get_inline(self.items.parent(key)?))
    }

    /// Generation of the latest build. Fragments it created, moved or resized
    /// have it as their [`geometry_generation`](super::Fragment::geometry_generation),
    /// and so do the [`subtree_generation`](super::Fragment::subtree_generation)
    /// of their ancestors.
    pub fn generation(&self) -> u64 {
        self.generation
    }

    pub fn clear(&mut self) {
        self.items.clear();
        self.states.clear();
        self.first.clear();
        self.changed.clear();
    }

    /// Start the generation of a new build.
    pub(crate) fn begin_generation(&mut self) {
        self.generation += 1;
        self.changed.clear();
    }

    /// Mark a fragment as created, moved or resized in the current build.
    pub(crate) fn record_geometry(&mut self, key: FragmentKey) {
        record_geometry(&mut self.items, &mut self.changed, self.generation, key);
    }

    /// Set the subtree generation of the fragments changed in this build and
    /// of their ancestors, once the tree is final.
    pub(crate) fn finish_generation(&mut self) {
        let generation = self.generation;

        for key in self.changed.drain(..) {
            let mut current = Some(key);

            while let Some(key) = current {
                let Some(fragment) = self.items.get_mut(key) else {
                    break;
                };

                // Ancestors of a marked fragment are marked already.
                if fragment.subtree_generation == generation {
                    break;
                }

                fragment.subtree_generation = generation;
                current = self.items.parent(key);
            }
        }
    }

    /// Insert a box or anonymous block fragment with its layout state, linking
    /// the two. `item` builds the fragment's item from the new state key.
    pub(crate) fn insert_with_state(
        &mut self,
        source: LayoutInputKey,
        item: impl FnOnce(StateKey) -> FragmentItem,
        state: NodeState,
    ) -> FragmentKey {
        let key = self.states.insert(state);
        let fragment = self
            .items
            .insert(Fragment::new(source, item(key), FragmentBox::default()));
        if let Some(state) = self.states.get_mut(key) {
            state.fragment = fragment;
        }
        self.record_geometry(fragment);

        fragment
    }

    /// The layout state of a box or anonymous block fragment.
    pub(crate) fn get_state(&self, fragment: FragmentKey) -> Option<&NodeState> {
        self.states.get(self.items.get(fragment)?.item.state()?)
    }

    pub(crate) fn get_state_mut(&mut self, fragment: FragmentKey) -> Option<&mut NodeState> {
        self.states.get_mut(self.items.get(fragment)?.item.state()?)
    }

    /// The style of a box or anonymous block fragment.
    ///
    /// # Panics
    /// If the fragment has no state.
    pub(crate) fn style(&self, fragment: FragmentKey) -> &Style {
        &self
            .get_state(fragment)
            .expect("fragment without layout state")
            .style
    }

    /// The inline layout owned by a box or anonymous block fragment.
    pub(crate) fn get_inline(&self, fragment: FragmentKey) -> Option<&InlineLayout> {
        self.get_state(fragment)?.inline.as_deref()
    }

    pub(crate) fn get_inline_mut(&mut self, fragment: FragmentKey) -> Option<&mut InlineLayout> {
        self.get_state_mut(fragment)?.inline.as_deref_mut()
    }

    /// Remove the inline layout owned by a fragment.
    pub(crate) fn take_inline(&mut self, fragment: FragmentKey) -> Option<Box<InlineLayout>> {
        self.get_state_mut(fragment)?.inline.take()
    }
}

/// Mark a fragment of `items` as created, moved or resized in `generation`.
pub(crate) fn record_geometry(
    items: &mut SlotTree<FragmentKey, Fragment>,
    changed: &mut Vec<FragmentKey>,
    generation: u64,
    key: FragmentKey,
) {
    if let Some(fragment) = items.get_mut(key)
        && fragment.geometry_generation != generation
    {
        fragment.geometry_generation = generation;
        changed.push(key);
    }
}
