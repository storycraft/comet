//! Layout and paint state of a window.
//!
//! The retained trees are grouped in [`UiTrees`], and the builders filling
//! them in [`UiBuilders`]. Both are public, so consumers can read the trees
//! and drive their own steps from them.

use accesskit::{NodeId, TreeId, TreeInfo, TreeUpdate};
use comet_accesskit::{AxKey, ax_key, builder::AxTreeBuilder, node_id, tree::AxTree};
use comet_content::manager::ContentManager;
use comet_geometry::{Size, UnitResolveContext};
use comet_layout::{
    dirty_map::DirtyMap,
    fragment::{BoxFragmentKey, FragmentRef, builder::FragmentTreeBuilder, tree::FragmentTree},
    input::{
        LayoutInputKey,
        builder::{BuildRequest, LayoutInputTreeBuilder},
        tree::LayoutInputTree,
    },
    style::LayoutConstraint,
};
use comet_paint::{
    hit::PaintHitTester,
    layer::{PaintLayerKey, builder::PaintLayerBuilder, tree::PaintLayerTree},
    painter::CometCompositePainter,
    prepaint::{builder::PrepaintTreeBuilder, fragment::BoxRole, tree::PrepaintTree},
    selection::{Selection, rects::SelectionRects},
};
use comet_reactivity::{prop::PropHint, tree::UiTree};
use comet_tree::{node::NodeKey, ui::Ui};
use kurbo::{Affine, Point, Vec2};

/// Font size of the root element, used for `rem`.
pub const ROOT_FONT_SIZE: f64 = 16.0;

/// The trees retained between layouts.
#[derive(Default)]
pub struct UiTrees {
    /// Layout items of the UI.
    pub inputs: LayoutInputTree,
    /// Changes taken from the UI and not consumed by the layout yet.
    pub dirty: DirtyMap,
    pub fragments: FragmentTree,
    pub prepaint: PrepaintTree,
    /// Rectangles behind the selected text, built with every layout.
    pub selection: SelectionRects,
    pub layers: PaintLayerTree,
    /// Accessibility nodes, built while accessibility is active.
    pub ax: AxTree,
}

impl UiTrees {
    /// The node of a layout item.
    pub fn node(&self, item: LayoutInputKey) -> Option<NodeKey> {
        Some(self.inputs.items.get(item)?.node)
    }

    /// The node of a fragment: the node of its source item. Anonymous run
    /// boxes have the node of the box they split.
    pub fn fragment_node(&self, fragment: FragmentRef) -> Option<NodeKey> {
        self.node(self.fragments.source(fragment)?)
    }

    /// The box fragment of `node`, from the last layout. Inline elements and
    /// texts in an inline flow have none.
    pub fn box_fragment(&self, node: NodeKey) -> Option<BoxFragmentKey> {
        self.fragments
            .box_fragment(self.inputs.item_for_node(node)?)
    }

    /// Whether the box `key` is generated by its source item itself: not an
    /// inline part or anonymous run box.
    pub fn is_principal(&self, key: BoxFragmentKey) -> bool {
        self.fragments
            .get(key)
            .is_some_and(|fragment| BoxRole::of(fragment).is_principal())
    }

    /// Maps the local coordinates of the box `key` to those of its parent
    /// box, from the last layout: see [`PaintLayerTree::transform`].
    pub fn transform(&self, key: BoxFragmentKey) -> Option<Affine> {
        self.layers.transform(&self.fragments, key)
    }

    /// The scroll offset the box `key` applies to its contents, from the
    /// last layout.
    pub fn scroll(&self, key: BoxFragmentKey) -> Vec2 {
        self.layers.scroll_offset(key)
    }

    /// How far the box of `node` can scroll, in logical units, from the last
    /// layout: see [`FragmentTree::scroll_range`]. `None` without a box
    /// fragment.
    pub fn scroll_range(&self, node: NodeKey) -> Option<Vec2> {
        self.fragments.scroll_range(self.box_fragment(node)?)
    }

    /// The box fragment of `node` if it owns an inline layout: it is the
    /// box of an inline formatting context, without block boxes inside. A
    /// box whose inline content is split by blocks owns none: its anonymous
    /// run boxes do.
    pub fn inline_owner(&self, node: NodeKey) -> Option<BoxFragmentKey> {
        let fragment = self.box_fragment(node)?;
        self.fragments.inline_layout(fragment)?;

        Some(fragment)
    }

    /// Maps the local coordinates of the box `key` to scene coordinates, in
    /// logical units: the transforms and scroll offsets of the box and its
    /// ancestors, from the last layout.
    pub fn fragment_to_scene(&self, key: BoxFragmentKey) -> Option<Affine> {
        let boxes = &self.fragments.boxes;
        let mut affine = self.transform(key)?;
        let mut next = boxes.parent(key);

        while let Some(key) = next {
            affine = self.transform(key)? * Affine::translate(-self.scroll(key)) * affine;
            next = boxes.parent(key);
        }

        Some(affine)
    }

    /// Maps the scrolled contents of the box `key`, where its children and
    /// inline items are placed, to scene coordinates.
    pub fn contents_to_scene(&self, key: BoxFragmentKey) -> Option<Affine> {
        Some(self.fragment_to_scene(key)? * Affine::translate(-self.scroll(key)))
    }

    /// Maps the local coordinates of a fragment to scene coordinates, like
    /// [`fragment_to_scene`](Self::fragment_to_scene). An inline item is at
    /// its location in the scrolled contents of the box owning its inline
    /// layout.
    pub fn fragment_ref_to_scene(&self, fragment: FragmentRef) -> Option<Affine> {
        match fragment {
            FragmentRef::Box(key) => self.fragment_to_scene(key),
            FragmentRef::Inline { owner, .. } => {
                let location = self.fragments.geometry(fragment)?.location;

                Some(self.contents_to_scene(owner)? * Affine::translate((location.x, location.y)))
            }
        }
    }

    /// Maps the coordinates of the inline layout owned by `owner` to scene
    /// coordinates, like [`fragment_to_scene`](Self::fragment_to_scene). The
    /// inline layout is placed in the scrolled contents of its owner.
    pub fn inline_to_scene(&self, owner: BoxFragmentKey) -> Option<Affine> {
        let origin = self.fragments.inline_layout(owner)?.origin();

        Some(self.contents_to_scene(owner)? * Affine::translate(origin))
    }
}

/// The builders filling [`UiTrees`], kept to reuse their buffers.
#[derive(Default)]
pub struct UiBuilders {
    pub inputs: LayoutInputTreeBuilder,
    pub fragments: FragmentTreeBuilder,
    pub prepaint: PrepaintTreeBuilder,
    pub layers: PaintLayerBuilder,
    pub hit_tester: PaintHitTester,
    pub painter: CometCompositePainter,
    pub ax: AxTreeBuilder,
}

/// A fragment hit by [`Pipeline::hit`], or on the path to it from
/// [`Pipeline::hit_path`], with its node.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Hit {
    pub node: NodeKey,
    /// The fragment, of `node`: a box, or an item of an inline layout, such
    /// as a piece of an inline element or a glyph run of a text.
    pub fragment: FragmentRef,
    /// The point in the local coordinates of `fragment`: of the border box
    /// of a box, before its scroll offset, or of the border box of an
    /// inline item.
    pub position: Point,
}

/// Every step is incremental: a layout without changes or a new viewport
/// does little work.
#[derive(Default)]
pub struct Pipeline {
    pub trees: UiTrees,
    pub builders: UiBuilders,
    /// Fonts the layout shapes text with.
    pub fonts: parley::FontContext,
    /// Root layer of the layers, from the last layout. `None` until a layout
    /// succeeds, or after one fails.
    layer_root: Option<PaintLayerKey>,
    /// Logical viewport of the last successful layout.
    viewport: Option<Size<f64>>,
    /// Scale factor of the last successful layout.
    scale_factor: Option<f64>,
    /// Logical viewport the input tree was resolved with, kept when a later
    /// step of the layout fails.
    input_viewport: Option<Size<f64>>,
    /// Logical viewport the pre-paint tree was last resolved with, kept when
    /// a resolve fails, so the next one resolves viewport units again.
    prepaint_viewport: Option<Size<f64>>,
    /// Logical viewport the layer tree was last built with, kept when a
    /// build fails, so the next one resolves viewport units again.
    layer_viewport: Option<Size<f64>>,
    /// Text selection painted with the layout.
    selection: Option<Selection>,
    a11y: Accessibility,
}

/// State of the accessibility tree, built with the layout while an
/// assistive technology is active.
#[derive(Default)]
struct Accessibility {
    active: bool,
    /// Root node of the last successful build. `None` until one succeeds,
    /// or after one fails.
    root: Option<AxKey>,
    /// Scale factor of the last update, applied to the root node.
    scale_factor: Option<f64>,
    /// Focus of the last update.
    focus: Option<NodeId>,
    /// Nodes with accessibility changes taken from the UI, marked in the
    /// tree by the next build.
    marks: Vec<NodeKey>,
}

impl Pipeline {
    /// Root layer of the last successful layout.
    pub fn layer_root(&self) -> Option<PaintLayerKey> {
        self.layer_root
    }

    /// Logical viewport of the last successful layout.
    pub fn viewport(&self) -> Option<Size<f64>> {
        self.viewport
    }

    /// The text selection painted with the layout.
    pub fn selection(&self) -> Option<Selection> {
        self.selection
    }

    /// Set the text selection painted with the layout, from the next
    /// layout on.
    pub fn set_selection(&mut self, selection: Option<Selection>) {
        self.selection = selection;
    }

    /// Take the changes recorded in `tree`, to be consumed by the next
    /// layout: layout flags are marked on the layout items, and nodes with
    /// accessibility changes are kept to be marked in the accessibility
    /// tree. Nodes not laid out yet have nothing to mark: a new node is laid
    /// out with the children of its parent.
    pub fn take_changes(&mut self, tree: &mut UiTree) {
        for (node, hint) in tree.take_changes() {
            if hint.contains(PropHint::A11Y) && self.a11y.active {
                self.a11y.marks.push(node);
            }

            let layout = hint.layout();
            if !layout.is_empty() {
                self.trees.dirty.mark_node(&self.trees.inputs, node, layout);
            }
        }
    }

    /// Take the changes of `tree`, then lay them out at `viewport`, in
    /// logical units, on a display of `scale_factor` physical pixels per
    /// logical unit, and place the layers. On failure, nothing is painted
    /// until a later layout succeeds.
    pub fn layout(
        &mut self,
        tree: &mut UiTree,
        root: NodeKey,
        viewport: Size<f64>,
        scale_factor: f64,
    ) -> Option<()> {
        self.take_changes(tree);
        let ui = &tree.ui;
        let contents = &tree.contents;
        let UiTrees {
            inputs,
            dirty,
            fragments,
            prepaint,
            selection,
            layers,
            ..
        } = &mut self.trees;
        let builders = &mut self.builders;
        // Cleared until the layout succeeds.
        let previous_viewport = self.viewport.take();
        let previous_scale_factor = self.scale_factor.take();
        // Cleared until the layers are placed. The layer tree keeps the root
        // layer, so the layers keep their keys.
        self.layer_root = None;

        // The first layout builds the whole tree. Later ones resolve the
        // marked changes and, after resolving at another viewport, the items
        // whose text styles depend on it.
        if self
            .input_viewport
            .is_some_and(|previous| previous != viewport)
            && let Some(key) = inputs.item_for_node(root)
        {
            inputs.invalidate_viewport(dirty, key);
        }
        let request = BuildRequest::new(root, ROOT_FONT_SIZE, viewport);
        let input_root = builders
            .inputs
            .prepare()
            .ui(ui)
            .tree(inputs)
            .dirty(dirty)
            .request(request)
            .build()?;
        self.input_viewport = Some(viewport);

        // Contents measure with the scale factor, so a new one lays them
        // out again, as a new viewport does.
        let viewport_changed = previous_viewport.is_some_and(|previous| previous != viewport)
            || previous_scale_factor.is_some_and(|previous| previous != scale_factor);
        let constraint = LayoutConstraint::new_root(viewport, ROOT_FONT_SIZE, scale_factor)
            .with_viewport_changed(viewport_changed);
        let Some(fragment_root) = builders
            .fragments
            .prepare()
            .ui(ui)
            .tree(inputs)
            .contents(contents)
            .fonts(&mut self.fonts)
            .dirty(dirty)
            .root(input_root)
            .fragments(fragments)
            .constraint(&constraint)
            .build()
        else {
            dirty.clear(inputs, input_root);
            return None;
        };

        // Positions and clips follow the layout, so resolve the fragments of
        // the items it laid out, which it marked, and of the other marked
        // items.
        let resolved = resolve_prepaint(
            &mut self.prepaint_viewport,
            builders,
            ui,
            inputs,
            dirty,
            fragments,
            prepaint,
            &constraint.units,
            fragment_root,
        );

        // Selection rects follow the inline layouts, so they are built with
        // every layout.
        if resolved.is_some() {
            selection
                .prepare()
                .ui(ui)
                .inputs(inputs)
                .fragments(fragments)
                .prepaint(prepaint)
                .root(fragment_root)
                .maybe_selection(self.selection)
                .build();
        }

        // Layers keep their keys, so building from the root again only places
        // the layers whose fragments gained, lost or reordered a layer. They
        // do not read the pre-paint tree, but are only built once it is
        // resolved, so a failed layout resolves both again.
        let layer_viewport_changed = self
            .layer_viewport
            .is_some_and(|previous| previous != viewport);
        let layer_root = resolved.and_then(|()| {
            builders
                .layers
                .prepare()
                .ui(ui)
                .inputs(inputs)
                .dirty(dirty)
                .fragments(&*fragments)
                .units(&constraint.units)
                .tree(layers)
                .root(input_root)
                .viewport_changed(layer_viewport_changed)
                .build()
        });
        if layer_root.is_some() {
            self.layer_viewport = Some(viewport);
        }
        // Flags were consumed by the fragment build, the pre-paint resolve,
        // the layer build and the accessibility build. On failure they are kept, so the
        // next layout resolves the items laid out by this one again.
        self.layer_root = Some(layer_root?);
        self.build_accessibility(ui, input_root);
        self.trees.dirty.clear(&self.trees.inputs, input_root);
        self.viewport = Some(viewport);
        self.scale_factor = Some(scale_factor);

        Some(())
    }

    /// Paint the last layout of `ui` into `scene`, covering `physical`, with
    /// the `contents` its nodes display.
    /// Does nothing until a layout succeeds.
    pub fn paint(
        &mut self,
        ui: &Ui,
        contents: &ContentManager,
        physical: kurbo::Rect,
        scale_factor: f64,
        scene: &mut impl anyrender::PaintScene,
    ) {
        let Some(layer_root) = self.layer_root else {
            return;
        };
        let trees = &self.trees;

        self.builders.painter.draw(
            ui,
            &trees.inputs,
            &trees.fragments,
            &trees.prepaint,
            &trees.selection,
            contents,
            &trees.layers,
            layer_root,
            physical,
            scale_factor,
            scene,
        );
    }

    /// The node under `point`, in logical units, from the last layout.
    pub fn hit(&mut self, point: Point) -> Option<Hit> {
        let trees = &self.trees;
        let hit = self.builders.hit_tester.hit(
            &trees.layers,
            &trees.fragments,
            &trees.prepaint,
            self.layer_root?,
            point,
        )?;
        Some(Hit {
            node: trees.fragment_node(hit.fragment)?,
            fragment: hit.fragment,
            position: hit.position,
        })
    }

    /// Fill `path` with the fragments on the path to the fragment under
    /// `point`, in logical units, from the last layout: from the root down,
    /// each with the point in its local coordinates. Empty when no fragment
    /// is under the point, or until a layout succeeds.
    pub fn hit_path(&mut self, point: Point, path: &mut Vec<Hit>) {
        path.clear();
        let Some(root) = self.layer_root else {
            return;
        };
        let trees = &self.trees;
        let mut cursor = self.builders.hit_tester.cursor(root, point);

        while let Some(hit) = cursor.hit_next(&trees.layers, &trees.fragments, &trees.prepaint) {
            let Some(node) = trees.fragment_node(hit.fragment) else {
                path.clear();
                return;
            };

            path.push(Hit {
                node,
                fragment: hit.fragment,
                position: hit.position,
            });
        }
    }
}

/// Resolve the pre-paint tree for the fragments under `root`, with paint
/// values using viewport units resolved again when `units` has another
/// viewport than the last successful resolve.
#[allow(clippy::too_many_arguments)]
fn resolve_prepaint(
    last_viewport: &mut Option<Size<f64>>,
    builders: &mut UiBuilders,
    ui: &Ui,
    inputs: &LayoutInputTree,
    dirty: &DirtyMap,
    fragments: &FragmentTree,
    prepaint: &mut PrepaintTree,
    units: &UnitResolveContext,
    root: BoxFragmentKey,
) -> Option<()> {
    let viewport_changed = last_viewport.is_some_and(|previous| previous != units.viewport);

    builders
        .prepaint
        .prepare()
        .ui(ui)
        .inputs(inputs)
        .dirty(dirty)
        .fragments(fragments)
        .units(units)
        .tree(prepaint)
        .root(root)
        .viewport_changed(viewport_changed)
        .build()?;
    *last_viewport = Some(units.viewport);

    Some(())
}

impl Pipeline {
    /// Start or stop building the accessibility tree. Starting builds the
    /// whole tree with the next layout, for the adapter's initial tree.
    pub fn set_accessibility(&mut self, active: bool) {
        self.trees.ax.clear();
        self.a11y = Accessibility {
            active,
            ..Default::default()
        };
    }

    pub fn accessibility_active(&self) -> bool {
        self.a11y.active
    }

    /// Build the accessibility tree for the last layout. A failed build
    /// starts over with the next one, which sends the whole tree again.
    fn build_accessibility(&mut self, ui: &Ui, root: LayoutInputKey) {
        let a11y = &mut self.a11y;
        if !a11y.active {
            return;
        }

        let trees = &mut self.trees;
        // Marked after the layout, on the items the nodes have now.
        for node in a11y.marks.drain(..) {
            trees.ax.mark_node(&trees.inputs, node);
        }

        a11y.root = self
            .builders
            .ax
            .prepare()
            .ui(ui)
            .inputs(&trees.inputs)
            .dirty(&trees.dirty)
            .fragments(&trees.fragments)
            .prepaint(&trees.prepaint)
            .layers(&trees.layers)
            .tree(&mut trees.ax)
            .root(root)
            .build();

        if a11y.root.is_none() {
            trees.ax.clear();
        }
    }

    /// The accessibility changes since the last update, with the root node
    /// scaled from logical units to the physical pixels of `scale_factor`,
    /// focusing the accessibility node of `focus` or of its nearest
    /// ancestor with one. `None` while inactive or without changes.
    pub fn take_accessibility_update(
        &mut self,
        ui: &Ui,
        scale_factor: f64,
        focus: Option<NodeKey>,
    ) -> Option<TreeUpdate> {
        let a11y = &mut self.a11y;
        let trees = &mut self.trees;
        let root = a11y.root.filter(|_| a11y.active)?;
        let root_id = node_id(root);
        let focus = core::iter::successors(focus, |&node| ui.parent(node))
            .find_map(|node| trees.ax.item_node(trees.inputs.item_for_node(node)?))
            .map_or(root_id, node_id);
        let mut nodes = trees.ax.take_update();

        // The root node carries the scale factor, so a new one updates it.
        if a11y.scale_factor != Some(scale_factor)
            && !nodes.iter().any(|(id, _)| *id == root_id)
            && let Some(node) = trees.ax.get(root)
        {
            nodes.push((root_id, node.node.clone()));
        }
        a11y.scale_factor = Some(scale_factor);

        if nodes.is_empty() && a11y.focus == Some(focus) {
            return None;
        }
        a11y.focus = Some(focus);

        for (_, node) in nodes.iter_mut().filter(|(id, _)| *id == root_id) {
            let transform = node.transform().map_or(Affine::IDENTITY, |transform| {
                Affine::new(transform.as_coeffs())
            });
            let scaled = Affine::scale(scale_factor) * transform;
            node.set_transform(accesskit::Affine::new(scaled.as_coeffs()));
        }

        Some(TreeUpdate {
            nodes,
            // Sending it again with every update is allowed.
            tree: Some(TreeInfo::new(root_id)),
            tree_id: TreeId::ROOT,
            focus,
        })
    }

    /// The source node of an accessibility node, such as the target of an
    /// action request.
    pub fn accessibility_target(&self, id: NodeId) -> Option<NodeKey> {
        let item = self.trees.ax.get(ax_key(id))?.item;

        self.trees.node(item)
    }
}
