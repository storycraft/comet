//! Paint data resolved for a fragment tree before painting.
//!
//! A [`PrePaintTree`](tree::PrePaintTree) holds the absolute position of
//! every fragment, and the [`LayoutInputData`] of every layout input item.
//! Fragments paint with the data of their source item, which follows the UI:
//! transforms and text colors are inherited from the parent item.

pub mod resolver;
pub mod tree;

use anyrender::Paint;
use kurbo::{Affine, Point, Rect};

/// Paint data of a layout input item, shared by all fragments it generates.
#[derive(Debug, Clone, PartialEq)]
pub struct LayoutInputData {
    /// Bounding box of the fragments generated by the item and linked
    /// together, such as its box, or its inline and glyph run fragments across
    /// lines. Line boxes and anonymous blocks do not participate. Absolute,
    /// in layout coordinates before transforms.
    pub bounding_box: Rect,

    /// Maps absolute layout coordinates to scene coordinates. Includes the
    /// transforms of all ancestor items.
    pub transform: Affine,

    /// Absolute point of the bounding box the item's own transform is applied
    /// around, in layout coordinates. Its centre, unless a box sets
    /// [`TransformOrigin`](crate::style::TransformOrigin).
    pub transform_origin: Point,

    /// Text color, inherited from the parent item unless the item sets one.
    pub text_color: Paint,

    /// Axes a box clips its contents on, to its bounding box.
    pub clip: (bool, bool),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FragmentPosition {
    /// Absolute position of fragment box, in layout coordinates before
    /// transforms.
    pub position: Point,
}
