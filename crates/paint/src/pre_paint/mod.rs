//! Paint data resolved for a fragment tree before painting.
//!
//! A [`PrePaintTree`](tree::PrePaintTree) holds the [`FragmentData`] of
//! every fragment, such as its absolute position, and the [`LayoutInputData`] of every layout input item.
//! Fragments paint with the data of their source item, which follows the UI:
//! transforms and text colors are inherited from the parent item.

pub mod resolver;
pub mod tree;

use anyrender::Paint;
use kurbo::{Affine, Point, Rect, RoundedRectRadii, Size};

/// Paint data of a layout input item, shared by all fragments it generates.
#[derive(Debug, Clone, PartialEq)]
pub struct LayoutInputData {
    /// Bounding box of the fragments generated by the item and linked
    /// together, such as its box, or its inline and glyph run fragments across
    /// lines. Line boxes and anonymous blocks do not participate. Absolute,
    /// in layout coordinates before transforms.
    pub bounding_box: Rect,

    /// Size of the fragments linked together in [`Self::bounding_box`], placed
    /// end to end as if the item was not split: box fragments below each
    /// other, inline and glyph run fragments side by side. Border radii
    /// resolve against it.
    pub stitched_size: Size,

    /// Maps absolute layout coordinates to scene coordinates. Includes the
    /// transforms of all ancestor items.
    pub transform: Affine,

    /// Inverse of [`Self::transform`], mapping scene coordinates back to
    /// absolute layout coordinates, such as for hit testing. `None` when the
    /// transform is not invertible, such as when it scales an axis to zero:
    /// the item then covers no area in the scene.
    pub inverse_transform: Option<Affine>,

    /// Absolute point of the bounding box the item's own transform is applied
    /// around, in layout coordinates. Its centre, unless a box sets
    /// [`TransformOrigin`](crate::style::TransformOrigin).
    pub transform_origin: Point,

    /// Text color, inherited from the parent item unless the item sets one.
    pub text_color: Paint,
}

/// Paint data of a fragment.
#[derive(Debug, Clone, PartialEq)]
pub struct FragmentData {
    /// Absolute position of fragment box, in layout coordinates before
    /// transforms.
    pub position: Point,

    /// Corner radii of the fragment's border box, resolved from its item's
    /// [`BorderRadius`](crate::style::BorderRadius) against the
    /// [stitched size](LayoutInputData::stitched_size) of its item. Corners
    /// joining a linked fragment are square. `None` for fragments painting no
    /// box, such as line boxes, or items setting no radius.
    pub border_radius: Option<RoundedRectRadii>,

    /// Axes a box fragment clips the contents of its item on, to its border
    /// box.
    pub clip: (bool, bool),
}
