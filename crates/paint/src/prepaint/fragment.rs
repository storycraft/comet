//! Queries of a [`FragmentTree`] for painting.
//!
//! Only box fragments are painted as boxes. Inline items that do not place a
//! box, such as lines and glyph runs, get no paint data. Their boxes are flat
//! children of the box owning the inline layout, so the inline elements
//! enclosing them are found through the items.

use comet_layout::{
    fragment2::{
        BoxFragment, BoxFragmentKey, BoxFragmentType, FragmentRef, FragmentTree, InlineLayout,
    },
    input::{LayoutInputKey, tree::LayoutInputTree},
};

/// What a box fragment paints, from its [`BoxFragmentType`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BoxRole {
    /// The box generated by its source item. It paints its background,
    /// border and outline, and applies its transform, clip and scroll.
    Principal,
    /// [Inline part](BoxFragmentType::InlinePart) box decorating a piece of
    /// an inline element. It paints the background, border and outline of
    /// the piece, but applies no transform, clip or scroll.
    InlinePart,
    /// [Anonymous](BoxFragmentType::Anonymous) box wrapping content of its
    /// source. It paints nothing and only positions its content.
    Anonymous,
}

impl BoxRole {
    pub const fn of(fragment: &BoxFragment) -> Self {
        match fragment.box_type {
            BoxFragmentType::InlinePart => Self::InlinePart,
            BoxFragmentType::Anonymous => Self::Anonymous,
            _ => Self::Principal,
        }
    }

    /// Whether the box paints a background, border and outline.
    pub const fn decorates(self) -> bool {
        !matches!(self, Self::Anonymous)
    }

    /// Whether the box applies the transform, clip and scroll of its item.
    pub const fn is_principal(self) -> bool {
        matches!(self, Self::Principal)
    }
}

/// The box fragments painting `item` of `inputs`: its box, or the
/// [inline part](BoxFragmentType::InlinePart) boxes of an inline element, in
/// layout order.
pub fn boxes_of<'a>(
    fragments: &'a FragmentTree,
    inputs: &'a LayoutInputTree,
    item: LayoutInputKey,
) -> impl Iterator<Item = BoxFragmentKey> + 'a {
    let own = fragments.box_fragment(item);
    let parts = own
        .is_none()
        .then(|| fragments.inline_boxes(inputs, item))
        .into_iter()
        .flatten();

    own.into_iter().chain(parts)
}

/// Index of the parent of the item `index` of `inline`: the line or piece
/// of an inline element holding it. `None` for lines.
pub fn inline_parent(inline: &InlineLayout, index: usize) -> Option<usize> {
    // Subtrees follow their roots, so the nearest item before `index`
    // covering it is its parent.
    (0..index)
        .rev()
        .find(|&i| i + inline.items[i].descendants as usize >= index)
}

/// Index of the item of `inline` placing the box `key`: an atomic inline or
/// an inline part box.
pub fn item_of_box(inline: &InlineLayout, key: BoxFragmentKey) -> Option<usize> {
    inline
        .items
        .iter()
        .position(|item| item.child_box() == Some(key))
}

/// The inline part box of the nearest piece of an inline element holding
/// the item `index` of `inline`, excluding the item itself.
pub fn enclosing_part(inline: &InlineLayout, index: usize) -> Option<BoxFragmentKey> {
    std::iter::successors(inline_parent(inline, index), |&index| {
        inline_parent(inline, index)
    })
    .find_map(|index| inline.items[index].child_box())
}

/// The parent of a fragment in paint order: the inline part box of the
/// inline element piece holding it, else its parent box. An inline item's
/// parent is the owner of its layout when no piece holds it. Lines are
/// skipped, as they paint nothing. `None` for the root box.
///
/// Not the parent coordinates are relative to: inline part boxes, the boxes
/// they hold and inline items are all placed relative to the border box of
/// the owner of their inline layout, so their transforms do not compose
/// along paint parents.
pub fn paint_parent(fragments: &FragmentTree, fragment: FragmentRef) -> Option<FragmentRef> {
    let (owner, part) = match fragment {
        FragmentRef::Inline { owner, index } => {
            let inline = fragments.inline_layout(owner)?;
            (owner, enclosing_part(inline, index as usize))
        }
        FragmentRef::Box(key) => {
            let owner = fragments.boxes.parent(key)?;
            let part = fragments
                .inline_layout(owner)
                .and_then(|inline| enclosing_part(inline, item_of_box(inline, key)?));
            (owner, part)
        }
    };

    Some(FragmentRef::Box(part.unwrap_or(owner)))
}
